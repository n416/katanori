def gloss_steps():
    """呼び名 → その語が出てくる手順の番号（本文を読んで拾う）"""
    import re
    hit = {}
    for name, *_ in GLOSS:
        pat = GLOSS_RE.get(name) or re.escape(re.split(r'[（ ]', name)[0])
        rx = re.compile(pat)
        ns = []
        for st in STEPS:
            body = ' '.join(st['acts']) + ' ' + st.get('warn', '') + ' ' + st.get('note', '') + ' ' + st.get('open_', '')
            body = re.sub(r'<[^>]*>', '', body)
            if rx.search(body):
                ns.append(st['n'])
        hit[name] = ns
    return hit



def mark_terms(chunks):
    """手順の本文に出てくる呼び名の**最初の 1 回**へ電球を付ける。
       タグの中は触らない。長い呼び名から先に当てる（「留め帯」を「帯」に食われないように）。"""
    import re, html as _h
    order = sorted([g[0] for g in GLOSS], key=len, reverse=True)
    pats = {n: re.compile(GLOSS_RE.get(n) or re.escape(re.split(r'[（ ]', n)[0])) for n in order}
    done, slots, out = set(), [], []
    for text in chunks:
        parts = re.split(r'(<[^>]*>)', text)
        for i, ch in enumerate(parts):
            if not ch or ch.startswith('<'):
                continue
            for name in order:
                if name in done:
                    continue
                m = pats[name].search(ch)
                if m:
                    slots.append((name, m.group(0)))
                    ch = ch[:m.start()] + ('@@T%d@@' % (len(slots) - 1)) + ch[m.end():]
                    done.add(name)
            parts[i] = ch
        out.append(''.join(parts))
    joined = '@@SPLIT@@'.join(out)
    for i, (name, txt) in enumerate(slots):
        e = _h.escape(name, True)
        joined = joined.replace('@@T%d@@' % i,
            '<span class="term">{}<button class="bulb" data-term="{}" '
            'aria-label="{} の絵を見る" title="{} の絵を見る">&#128161;</button></span>'
            .format(txt, e, e, e))
    return joined.split('@@SPLIT@@')


